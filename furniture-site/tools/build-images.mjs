/**
 * Builds the local image set: responsive WebP + JPEG fallbacks for every
 * gallery piece, a social-sharing cover, and the app icons.
 *
 * Run with `node tools/build-images.mjs` whenever the curated photographs in
 * src/showcase.js change. Existing complete sets are skipped, so adding a few
 * pieces does not re-download the whole catalogue. Pass `--force` to rebuild
 * everything. The output lives in public/assets/img/gallery.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { SHOWCASE } from '../src/showcase.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'public/assets/img/gallery');
const iconDir = path.join(root, 'public/assets/img');
fs.mkdirSync(outDir, { recursive: true });

const WIDTHS = [480, 960];
const force = process.argv.includes('--force');

async function download(url) {
  const res = await fetch(url, {
    headers: { 'user-agent': 'FineFurniture image builder', accept: 'image/*' },
  });
  if (!res.ok) throw new Error(`Image request failed (${res.status}): ${url}`);
  return Buffer.from(await res.arrayBuffer());
}

async function readSource(piece) {
  const src = piece.source || piece.image;
  if (/^https?:/i.test(src)) return download(src);
  const local = path.join(root, 'public', src.replace(/^\//, ''));
  if (fs.existsSync(local)) return fs.readFileSync(local);
  throw new Error(`No local source for ${piece.slug}`);
}

let meta = {};
try {
  meta = JSON.parse(fs.readFileSync(path.join(outDir, 'sizes.json'), 'utf8'));
} catch {
  meta = {};
}

const failures = [];

for (const piece of SHOWCASE) {
  const name = piece.slug + (piece.rev ? '-' + piece.rev : '');
  const files = WIDTHS.map((w) => path.join(outDir, `${name}-${w}.webp`));
  if (!force && files.every((file) => fs.existsSync(file))) {
    if (!meta[piece.slug]) {
      try {
        const info = await sharp(files[files.length - 1]).metadata();
        meta[piece.slug] = { w: info.width, h: info.height };
      } catch {
        /* metadata can be rebuilt later */
      }
    }
    continue;
  }
  try {
    const source = await readSource(piece);
    for (const width of WIDTHS) {
      const pipe = sharp(source).rotate().resize({ width, withoutEnlargement: true });
      await pipe.clone().webp({ quality: width === 960 ? 66 : 60, effort: 6 }).toFile(path.join(outDir, `${name}-${width}.webp`));
    }
    const info = await sharp(source).metadata();
    meta[piece.slug] = { w: info.width, h: info.height };
    console.log('built', name, info.width + '×' + info.height);
  } catch (error) {
    failures.push(name + ': ' + error.message);
  }
}

if (!failures.length) {
  // Social cover from the hero sofa (the first photographed piece).
  const hero = SHOWCASE.find((p) => p.category === 'sofas' && p.featured) || SHOWCASE.find((p) => p.category === 'sofas') || SHOWCASE[0];
  const heroSource = await readSource(hero);
  await sharp(heroSource).rotate().resize({ width: 1200, height: 630, fit: 'cover', position: 'attention' })
    .jpeg({ quality: 82, mozjpeg: true }).toFile(path.join(iconDir, 'og-cover.jpg'));
  await sharp(heroSource).rotate().resize({ width: 1200, height: 630, fit: 'cover', position: 'attention' })
    .webp({ quality: 78 }).toFile(path.join(iconDir, 'og-cover.webp'));

  await sharp(fs.readFileSync(path.join(iconDir, 'logo.svg')))
    .resize(180, 180, { fit: 'contain', background: '#f7f2ea' })
    .png().toFile(path.join(iconDir, 'apple-touch-icon.png'));
  await sharp(fs.readFileSync(path.join(iconDir, 'logo.svg')))
    .resize(192, 192, { fit: 'contain', background: '#f7f2ea' })
    .png().toFile(path.join(iconDir, 'icon-192.png'));
  await sharp(fs.readFileSync(path.join(iconDir, 'logo.svg')))
    .resize(512, 512, { fit: 'contain', background: '#f7f2ea' })
    .png().toFile(path.join(iconDir, 'icon-512.png'));

  // Intrinsic sizes let the client emit width/height and avoid layout shift.
  fs.writeFileSync(
    path.join(root, 'public/assets/js/images.js'),
    '/* Generated by tools/build-images.mjs — intrinsic photo sizes. */\n' +
      'window.FF = window.FF || {};\n' +
      'window.FF.IMAGE_META = ' + JSON.stringify(meta, null, 2) + ';\n'
  );
  fs.writeFileSync(path.join(outDir, 'sizes.json'), JSON.stringify(meta, null, 2));
}

console.log(failures.length ? 'FAILURES:\n' + failures.join('\n') : 'all images built');
process.exit(failures.length ? 1 : 0);
