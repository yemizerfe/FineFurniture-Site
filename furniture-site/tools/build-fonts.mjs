/**
 * Downloads the Latin and Ethiopic font files the design uses and writes a
 * local @font-face sheet, so the site no longer depends on Google Fonts at
 * runtime. Run with `node tools/build-fonts.mjs` when the type changes.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const fontDir = path.join(root, 'public/assets/fonts');
fs.mkdirSync(fontDir, { recursive: true });

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';
const CSS_URL =
  'https://fonts.googleapis.com/css2?' +
  'family=Fraunces:ital,opsz,wght@0,9..144,300..900;1,9..144,300..900&' +
  'family=Inter:wght@300..700&' +
  'family=Noto+Serif+Ethiopic:wght@400..700&display=swap';

const css = await (await fetch(CSS_URL, { headers: { 'user-agent': UA } })).text();

const blocks = [];
const re = /\/\*\s*([a-z0-9-]+)\s*\*\/\s*(@font-face\s*{[^}]+})/g;
let match;
while ((match = re.exec(css))) blocks.push({ subset: match[1], body: match[2] });
if (!blocks.length) {
  console.error('Google Fonts did not return labelled @font-face blocks.');
  process.exit(1);
}

const keep = blocks.filter((b) => b.subset === 'latin' || b.subset === 'ethiopic');
const files = [];
const out = [];
const seen = new Map();

for (const block of keep) {
  const family = (block.body.match(/font-family:\s*'([^']+)'/) || [])[1] || 'font';
  const style = (block.body.match(/font-style:\s*([a-z]+)/) || [])[1] || 'normal';
  const weight = (block.body.match(/font-weight:\s*([^;]+);/) || [])[1] || '400';
  const range = (block.body.match(/unicode-range:\s*([^;]+);/) || [])[1] || '';
  const url = (block.body.match(/url\((https:[^)]+\.woff2)\)/) || [])[1];
  if (!url) continue;

  const slug = `${family.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-${style}-${block.subset}`;
  const file = `${slug}.woff2`;
  const target = path.join(fontDir, file);
  if (!seen.has(url)) {
    const bytes = Buffer.from(await (await fetch(url, { headers: { 'user-agent': UA } })).arrayBuffer());
    fs.writeFileSync(target, bytes);
    seen.set(url, { file, bytes: bytes.length });
    files.push({ file, bytes: bytes.length, family, style, subset: block.subset });
  }
  out.push(
    `@font-face {\n  font-family: '${family}';\n  font-style: ${style};\n  font-weight: ${weight};\n  font-display: swap;\n  src: url('/assets/fonts/${seen.get(url).file}') format('woff2');\n` +
      (range ? `  unicode-range: ${range};\n` : '') +
      '}'
  );
}

fs.writeFileSync(
  path.join(root, 'public/assets/css/fonts.css'),
  '/* Generated by tools/build-fonts.mjs — self-hosted, swap, no third party. */\n' + out.join('\n\n') + '\n'
);

const total = files.reduce((n, f) => n + f.bytes, 0);
console.log(files.map((f) => `  ${f.file}  ${(f.bytes / 1024).toFixed(1)} kB`).join('\n'));
console.log(`fonts: ${files.length} files, ${(total / 1024).toFixed(1)} kB total`);
